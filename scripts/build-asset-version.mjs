// Builds _data/asset_version.yml: one short content hash used as ?v= on main.css, site.js and the lazy
// top-menu fragment (assets/menu-in.html), instead of the build time.
//   node scripts/build-asset-version.mjs [--check]
//
// Why (India cleanup, 2026-10-30): GitHub Pages serves every file with max-age=600 + an ETag. With
// ?v={{ site.time }} the URL changed on every deploy, so every returning visitor downloaded the full
// 312 KB stylesheet and 113 KB script again after each commit. With a content hash the URL only changes
// when those files (or the data Liquid writes into them) change; otherwise the browser gets a cheap 304.
// A stale hash is harmless (the browser revalidates after 10 minutes anyway), but --check exits 1 so
// verify runs catch it. Rerun after editing any INPUTS file.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, '_data', 'asset_version.yml');
// Files whose content ends up in the versioned assets (site.js and the menu fragment are Liquid-rendered).
export const INPUTS = [
  'assets/css/main.css',
  'assets/js/site.js',
  'assets/menu-in.html',
  '_includes/in-header-hubs.html',
  '_data/nav.yml',
  '_data/nav_mega.yml',
  '_data/regions.yml',
  '_data/search.yml',
  '_data/explorer.yml',
];

export function assetVersion() {
  const h = crypto.createHash('sha256');
  for (const f of INPUTS) {
    const p = path.join(root, f);
    h.update(f + '\0' + (fs.existsSync(p) ? fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n') : '') + '\0');
  }
  return h.digest('hex').slice(0, 10);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const v = assetVersion();
  const text = `# GENERATED by scripts/build-asset-version.mjs — do not edit by hand.\n# Content hash of the files listed in that script; used as ?v= on main.css, site.js and assets/menu-in.html.\nv: "${v}"\n`;
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (old !== text) { console.error(`_data/asset_version.yml is stale (want ${v}); run node scripts/build-asset-version.mjs`); process.exit(1); }
    console.log(`asset version ${v} up to date`);
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`asset version ${v}`);
  }
}
