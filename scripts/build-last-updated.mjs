// Builds _data/last_updated.yml: the "Last updated" date shown in the small stamp under the top menu
// (_includes/last-updated.html, placed by _layouts/default.html).
//   node scripts/build-last-updated.mjs [--check]
//
// A page's date = the newest of: the last commit that touched the page file, and the last commit that
// touched any data file the page is built from. Data files are found from the page itself:
//   front matter `career: x`                     -> _data/in/careers/x.yml
//   {% include something.html k="v" %}           -> any of _data/in/{careers,journey,states,abroad}/v.yml,
//                                                    _data/roadmaps/v.json that exists
//   includes that read one shared file           -> SHARED below (sport pages -> sports.yml, finders -> colleges/coaching)
// A file with uncommitted changes counts as changed today, so run this last, right before committing.
// Redirect stubs (front matter redirect_to) get no date. --check exits 1 when the file on disk is stale.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const OUT = path.join(root, '_data', 'last_updated.yml');
const SKIP_DIRS = new Set(['_archive', '_data', '_includes', '_layouts', '_site', 'assets', 'scripts', 'node_modules', 'docs', 'design-system', 'redirects', '.git', '.github']);

const SHARED = {
  'sport-page.html': ['_data/in/sports.yml'],
  'sport-roadmap.html': ['_data/in/sports.yml'],
  'sports-guide.html': ['_data/in/sports_guides.yml'],
  'sports-atlas.html': ['_data/in/sports_atlas.yml'],
  'national-exam.html': ['_data/in/national_exams.yml'],
  'journey-doubts.html': ['_data/in/journey_common.yml'],
  'explorer.html': ['_data/colleges.yml', '_data/coaching.yml'],
  'finder.html': ['_data/colleges.yml', '_data/coaching.yml'],
  'seo-listing-renderer.html': ['_data/colleges.yml', '_data/coaching.yml'],
};
const PER_KEY = ['_data/in/careers/%.yml', '_data/in/journey/%.yml', '_data/in/states/%.yml', '_data/in/abroad/%.yml', '_data/roadmaps/%.json'];

// ---- newest commit date per file, from one pass over the history ----
const today = new Date().toLocaleDateString('en-CA'); // local YYYY-MM-DD, same clock as %cs
const last = new Map();
const log = execFileSync('git', ['-c', 'core.quotepath=false', 'log', '--format=@%cs', '--name-only', '--no-renames'], { cwd: root, maxBuffer: 1 << 30 }).toString();
let cur = null;
for (const line of log.split('\n')) {
  if (line.startsWith('@')) cur = line.slice(1);
  else if (line && !last.has(line)) last.set(line, cur);
}
const dirty = execFileSync('git', ['-c', 'core.quotepath=false', 'status', '--porcelain', '--untracked-files=all'], { cwd: root }).toString();
for (const line of dirty.split('\n')) {
  const f = line.slice(3).trim().replace(/^"|"$/g, '');
  if (f) last.set(f.includes(' -> ') ? f.split(' -> ')[1] : f, today);
}

// ---- pages ----
const pages = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const rel = dir ? `${dir}/${e.name}` : e.name;
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name) && !e.name.startsWith('.')) walk(rel); }
    else if (e.name.endsWith('.html')) pages.push(rel);
  }
};
walk('');

const out = {};
for (const rel of pages.sort()) {
  const src = fs.readFileSync(path.join(root, rel), 'utf8');
  if (!src.startsWith('---')) continue;
  const fm = src.slice(3, src.indexOf('\n---', 3));
  if (/^redirect_to:/m.test(fm)) continue;
  const deps = new Set([rel]);
  const career = fm.match(/^career:\s*"?([\w-]+)"?/m);
  if (career) deps.add(`_data/in/careers/${career[1]}.yml`);
  for (const m of src.matchAll(/{%-?\s*include\s+([\w-]+\.html)([^%]*)%}/g)) {
    for (const f of SHARED[m[1]] || []) deps.add(f);
    for (const v of m[2].matchAll(/\w+="([\w-]+)"/g)) {
      for (const p of PER_KEY) { const f = p.replace('%', v[1]); if (fs.existsSync(path.join(root, f))) deps.add(f); }
    }
  }
  let d = '';
  for (const f of deps) { const t = last.get(f); if (t && t > d) d = t; }
  if (d) out[rel] = d;
}

const body = '# Generated by scripts/build-last-updated.mjs — do not edit. Page path -> date of its last change\n'
  + '# (page file or the data it is built from). Read by _includes/last-updated.html.\n'
  + Object.entries(out).map(([k, v]) => `"${k}": "${v}"`).join('\n') + '\n';
const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (CHECK) {
  if (old !== body) { console.error('last_updated.yml is stale: run node scripts/build-last-updated.mjs'); process.exit(1); }
  console.log(`last_updated.yml OK (${Object.keys(out).length} pages)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${Object.keys(out).length} page dates to _data/last_updated.yml`);
}
